from __future__ import annotations

import time
from collections.abc import Sequence
from pathlib import Path
from typing import ClassVar, override

from flext_infra import c, m, t, u
from flext_infra.gates import FlextInfraGate


class FlextInfraLintConfigFreezeGate(FlextInfraGate):
    """Fail any drift of frozen lint-config tables from the operator catalog.

    The catalog is regenerated by the canonical modernizer run at the same
    publication that renders the projections; a working tree whose tables no
    longer match it is an unauthorized rule edit (operator order 2026-10-28,
    pyright incident) and blocks with the authorization message.
    """

    gate_id: ClassVar[str] = c.Infra.LINT_CONFIG_FREEZE
    gate_name: ClassVar[str] = c.Infra.SARIF_TOOL_INFO[gate_id][0]
    can_fix: ClassVar[bool] = False

    @classmethod
    def refresh_catalog(
        cls,
        root: Path,
        states: Sequence[m.Infra.PyprojectDocumentState],
    ) -> Sequence[str]:
        """Regenerate the operator catalog after a canonical projection run.

        Args:
            root: The workspace root owning the catalog file.
            states: Every scanned pyproject document state of the run.

        Returns:
            The change notes, or an empty sequence when nothing moved.

        """
        catalog = cls._catalog_path(root)
        digests: dict[str, t.JsonValue] = {
            cls._catalog_key(Path(state.pyproject_path).parent): cls._table_digest(
                state.payload,
            )
            for state in states
            if cls._frozen_tables(state.payload)
        }
        rendered = u.Cli.json_dumps(digests, sort_keys=True, indent=2).unwrap_or("{}")
        previous = (
            catalog.read_text(encoding=c.DEFAULT_ENCODING) if catalog.is_file() else ""
        )
        if rendered + "\n" == previous:
            return ()
        catalog.parent.mkdir(parents=True, exist_ok=True)
        catalog.write_text(rendered + "\n", encoding=c.DEFAULT_ENCODING)
        return (f"{catalog}: frozen lint-config digests updated",)

    @override
    def check(
        self,
        project_dir: Path,
        ctx: m.Infra.GateContext,
    ) -> m.Infra.GateExecution:
        """Compare this project's frozen tables against the operator catalog.

        Returns:
            The completed verdict with the authorization message on any drift.

        Raises:
            ValueError: If the project declares no readable pyproject or the
                catalog has not been generated yet.

        """
        started = time.monotonic()
        pyproject = project_dir / c.PYPROJECT_FILENAME
        payload = u.Infra.pyproject_payload(pyproject)
        if not payload:
            message = f"lint-config freeze requires a pyproject: {pyproject}"
            raise ValueError(message)
        digest = self._table_digest(payload)
        expected = self._catalog_digests(project_dir).get(
            self._catalog_key(project_dir),
        )
        issue = self._drift_issue(pyproject, expected, digest)
        issues: tuple[m.Infra.Issue, ...] = () if issue is None else (issue,)
        return self._build_gate_execution(
            m.Infra.GateExecutionParams(
                project_dir=project_dir,
                verdict=not issues,
                issues=issues,
                raw_output=f"digest={digest} expected={expected}",
                started=started,
            ),
            ctx,
        )

    @override
    def check_files(
        self,
        files: Sequence[Path],
        project_dir: Path,
        ctx: m.Infra.GateContext,
    ) -> m.Infra.GateExecution:
        """Check the project the supplied frozen files belong to.

        Returns:
            The catalog verdict for this project.

        """
        return self.check(project_dir, ctx)

    @classmethod
    def _catalog_path(cls, root: Path) -> Path:
        """Resolve the tracked catalog location for one workspace root.

        Returns:
            The catalog file under the flext-infra member's config directory.

        """
        return root / "flext-infra" / "config" / "lint_freeze_catalog.json"

    @classmethod
    def _catalog_digests(cls, project_dir: Path) -> t.JsonMapping:
        """Load the operator catalog generated by the canonical modernizer.

        Returns:
            The per-project frozen-table digests.

        Raises:
            ValueError: When the catalog file is absent (the verdict then
                fails closed: run the canonical generation publisher first).

        """
        candidates = (
            project_dir / "config" / "lint_freeze_catalog.json",
            cls._catalog_path(project_dir.parent),
            cls._catalog_path(project_dir),
        )
        for catalog in candidates:
            if catalog.is_file():
                return u.Cli.json_read(catalog).unwrap()
        message = (
            "lint-config freeze catalog is missing; run the canonical "
            f"generation publisher first: {project_dir}"
        )
        raise ValueError(message)

    @classmethod
    def _frozen_tables(cls, payload: t.JsonMapping) -> dict[str, t.JsonValue]:
        """Extract the frozen lint-config tables of one pyproject payload.

        Returns:
            The present frozen tables in the constant declaration order.

        """
        tool = u.Cli.toml_mapping_child(payload, c.Infra.TOOL) or {}
        return {
            table: tool[table] for table in cls._frozen_table_names() if table in tool
        }

    @classmethod
    def _table_digest(cls, payload: t.JsonMapping) -> str:
        """Digest one pyproject's frozen lint-config tables canonically.

        Returns:
            The sha256 of the sorted JSON encoding of the frozen tables.

        """
        canonical = u.Cli.json_dumps(
            cls._frozen_tables(payload),
            sort_keys=True,
        ).unwrap_or("{}")
        return u.Cli.sha256_bytes(canonical.encode(c.DEFAULT_ENCODING))[:16]

    @classmethod
    def _frozen_table_names(cls) -> Sequence[str]:
        """Read the frozen table names from the freeze constant order.

        Returns:
            The table names in their canonical order.

        """
        return ("pyright", "ruff", "mypy", "pyrefly")

    @staticmethod
    def _catalog_key(project_dir: Path) -> str:
        """Resolve the catalog key of one checked project.

        Returns:
            The member directory basename.

        """
        return project_dir.name

    @classmethod
    def _drift_issue(
        cls,
        pyproject: Path,
        expected: object,
        digest: str,
    ) -> m.Infra.Issue | None:
        """Build the blocking issue for one frozen-table drift.

        Returns:
            The operator-authorization diagnostic, or no issue when the live
            digest matches the catalog (or the entry is absent and the tree is
            untouched by the canonical publisher yet).

        """
        if expected is None:
            detail = "no catalog entry"
        elif expected != digest:
            detail = f"catalog={expected} live={digest}"
        else:
            return None
        return m.Infra.Issue(
            file=str(pyproject),
            line=1,
            column=1,
            code=f"{c.Infra.LINT_CONFIG_FREEZE}-drift",
            message=(
                "frozen lint-config table drifted from the operator catalog "
                f"({detail}); lint-rule changes require express operator "
                "authorization (AGENTS.md: Lint-Rule Change Freeze, 2026-10-28)"
            ),
            severity=c.Infra.GateSeverity.ERROR.value,
        )


__all__: list[str] = ["FlextInfraLintConfigFreezeGate"]
