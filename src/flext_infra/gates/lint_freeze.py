from __future__ import annotations

import time
from collections.abc import Sequence
from pathlib import Path
from typing import ClassVar, override

from flext_infra import c, m, t, u
from flext_infra.gates import FlextInfraGates


class FlextInfraGatesLintConfigFreeze(FlextInfraGates):
    """Fail any drift of frozen lint-config tables from the operator catalog.

    The catalog is regenerated by the canonical modernizer through the shared
    publisher; a working tree whose tables no longer match it is an
    unauthorized rule edit (operator order 2026-10-28,
    pyright incident) and blocks with the authorization message.
    """

    gate_id: ClassVar[str] = c.Infra.LINT_CONFIG_FREEZE
    gate_name: ClassVar[str] = c.Infra.SARIF_TOOL_INFO[gate_id][0]
    can_fix: ClassVar[bool] = False

    @classmethod
    def refresh_catalog(
        cls,
        root: Path,
        states: Sequence[m.Infra.PyprojectDocumentState],
        *,
        invalid_paths: Sequence[Path],
    ) -> Sequence[str]:
        """Publish observed digests without discarding unobserved projects.

        Only a complete governed inventory replaces the catalog. Partial runs
        update their own entries and preserve every other original digest.
        An existing digest cannot be replaced or removed by projection drift.
        The original captured catalog remains the publisher's preimage.

        Args:
            root: The workspace root owning the catalog file.
            states: Every scanned pyproject document state of the run.
            invalid_paths: Documents whose scan did not establish valid evidence.

        Returns:
            The change notes, or an empty sequence when nothing moved.

        Raises:
            ValueError: If the frozen lint-config catalog cannot be updated due to
              unauthorized changes, or if the catalog does not exist yet and the
              run is not one complete governed scan of every managed project.

        """
        inputs = u.Infra.load_codegen_inputs(root).unwrap()
        before = u.Cli.atomic_read_binary_file_state(
            root / inputs.spec.make.lint_freeze_catalog
        ).unwrap()
        created = before.content is None
        previous = {} if created else cls._catalog_values(before)
        observed = {state.pyproject_path.parent.resolve() for state in states}
        declared = u.Infra.repository_operation_targets(
            root, c.Infra.CodegenConformScope.ALL
        ).unwrap()
        expected = {
            target.root.resolve() for target in declared if target.managed is not False
        }
        if created and (invalid_paths or observed != expected):
            message = (
                "initial lint-config catalog requires one complete governed scan: "
                f"invalid_documents={len(invalid_paths)}, "
                f"missing_projects={sorted(expected - observed)}, "
                f"unexpected_projects={sorted(observed - expected)}"
            )
            raise ValueError(message)
        digests: dict[str, t.JsonValue] = (
            dict(previous) if invalid_paths or observed != expected else {}
        )
        for state in states:
            key = cls._catalog_key(state.pyproject_path.parent, state.payload)
            digest = (
                cls._table_digest(state.payload)
                if cls._frozen_tables(state.payload)
                else None
            )
            if not created and previous.get(key) != digest:
                message = (
                    f"frozen lint-config catalog cannot change the entry for {key}; "
                    "rule changes require express operator authorization"
                )
                raise ValueError(message)
            if digest is not None:
                digests[key] = digest
        rendered = (
            u.Cli.json_dumps(digests, sort_keys=True, indent=2).unwrap() + "\n"
        ).encode(c.DEFAULT_ENCODING)
        if rendered == before.content:
            return ()
        u.Infra.publish_codegen_plans(
            root,
            cls._catalog_plans(root, inputs, before, rendered),
        ).unwrap()
        return (f"{before.path}: frozen lint-config digests updated",)

    @override
    def check(
        self,
        project_dir: Path,
        ctx: m.Infra.GateContext,
    ) -> m.Infra.GateExecution:
        """Compare this project's frozen tables against the operator catalog.

        Returns:
            The completed verdict with the authorization message on any drift.

        Raises:
            ValueError: If the project declares no readable pyproject or the
                catalog has not been generated yet.

        """
        started = time.monotonic()
        pyproject = project_dir / c.PYPROJECT_FILENAME
        payload = u.Infra.pyproject_payload(pyproject)
        if not payload:
            message = f"lint-config freeze requires a pyproject: {pyproject}"
            raise ValueError(message)
        digest = self._table_digest(payload)
        expected = self._catalog_digests(ctx.repository_root).get(
            self._catalog_key(project_dir, payload),
        )
        issue = self._drift_issue(pyproject, expected, digest)
        issues: tuple[m.Infra.Issue, ...] = () if issue is None else (issue,)
        return self._build_gate_execution(
            m.Infra.GateExecutionParams(
                project_dir=project_dir,
                verdict=not issues,
                issues=issues,
                raw_output=f"digest={digest} expected={expected}",
                started=started,
            ),
            ctx,
        )

    @override
    def check_files(
        self,
        files: Sequence[Path],
        project_dir: Path,
        ctx: m.Infra.GateContext,
    ) -> m.Infra.GateExecution:
        """Check the project the supplied frozen files belong to.

        Returns:
            The catalog verdict for this project.

        """
        return self.check(project_dir, ctx)

    @classmethod
    def _catalog_digests(cls, root: Path) -> dict[str, str]:
        """Read the complete original catalog at the declared policy path.

        Returns:
            The per-project frozen-table digests.

        Raises:
            ValueError: If the catalog has not been generated yet.

        """
        inputs = u.Infra.load_codegen_inputs(root).unwrap()
        before = u.Cli.atomic_read_binary_file_state(
            root / inputs.spec.make.lint_freeze_catalog
        ).unwrap()
        if before.content is None:
            message = (
                "lint-config catalog has not been generated yet; run the "
                "canonical modernizer to publish the initial governed catalog"
            )
            raise ValueError(message)
        return cls._catalog_values(before)

    @staticmethod
    def _catalog_values(before: m.Cli.AtomicFileState) -> dict[str, str]:
        """Validate the complete original catalog through one strict contract.

        Returns:
            Every project digest from the captured original bytes.

        Raises:
            ValueError: If the required catalog has no captured content.

        """
        if before.content is None:
            message = f"required lint-config catalog has no content: {before.path}"
            raise ValueError(message)
        return u.type_adapter(dict[str, str]).validate_json(before.content, strict=True)

    @classmethod
    def require_projection(
        cls, root: Path, state: m.Infra.PyprojectDocumentState
    ) -> tuple[m.Infra.CodegenFilePlan, ...]:
        """Reject frozen candidate drift before any document publication.

        Returns:
            The unchanged catalog and configuration observations for the
            publisher, or nothing when the workspace has no catalog yet —
            the canonical modernizer publishes the initial governed catalog
            through ``refresh_catalog`` at the end of its run.

        Raises:
            ValueError: If the candidate differs from the original frozen digest.

        """
        inputs = u.Infra.load_codegen_inputs(root).unwrap()
        before = u.Cli.atomic_read_binary_file_state(
            root / inputs.spec.make.lint_freeze_catalog
        ).unwrap()
        if before.content is None:
            return ()
        key = cls._catalog_key(state.pyproject_path.parent, state.payload)
        issue = cls._drift_issue(
            state.pyproject_path,
            cls._catalog_values(before).get(key),
            cls._table_digest(state.payload),
        )
        if issue is not None:
            raise ValueError(issue.message)
        return cls._catalog_plans(root, inputs, before, before.content)

    @staticmethod
    def _catalog_plans(
        root: Path,
        inputs: m.Infra.CodegenInputs,
        before: m.Cli.AtomicFileState,
        content: bytes | None,
    ) -> tuple[m.Infra.CodegenFilePlan, ...]:
        """Retain original policy observations under their physical project owners.

        Returns:
            The catalog plan and unchanged configuration input plans.

        """
        plans: list[m.Infra.CodegenFilePlan] = []
        for observed, desired in (
            (before, content),
            *((source, source.content) for source in inputs.sources),
        ):
            ownership = u.Infra.git_mutation_scope(
                m.Infra.GitRepoRequest(repo_root=observed.path.parent)
            ).unwrap()
            project = (
                root
                if ownership.git_dir is None
                else u.Infra
                .git_show_toplevel(
                    m.Infra.GitRepoRequest(repo_root=observed.path.parent)
                )
                .unwrap()
                .repository_root
            )
            plans.append(
                m.Infra.CodegenFilePlan(
                    project=project,
                    path=observed.path,
                    before=observed,
                    desired_content=desired,
                    desired_mode=(
                        observed.mode if observed.mode is not None else 0o644
                    ),
                    owner=c.Infra.LINT_CONFIG_FREEZE,
                )
            )
        return tuple(plans)

    @classmethod
    def _frozen_tables(cls, payload: t.JsonMapping) -> dict[str, t.JsonValue]:
        """Extract the frozen lint-config tables of one pyproject payload.

        Returns:
            The present frozen tables in the constant declaration order.

        """
        tool = u.Cli.toml_mapping_child(payload, c.Infra.TOOL) or {}
        return {
            table: tool[table]
            for table in ("pyright", "ruff", "mypy", "pyrefly")
            if table in tool
        }

    @classmethod
    def _table_digest(cls, payload: t.JsonMapping) -> str:
        """Digest one pyproject's frozen lint-config tables canonically.

        Returns:
            The sha256 of the sorted JSON encoding of the frozen tables.

        """
        canonical = u.Cli.json_dumps(
            cls._frozen_tables(payload),
            sort_keys=True,
        ).unwrap()
        return u.Cli.sha256_bytes(canonical.encode(c.DEFAULT_ENCODING))[:16]

    @staticmethod
    def _catalog_key(project_dir: Path, payload: t.JsonMapping) -> str:
        """Resolve the catalog key of one checked project.

        Returns:
            The project identity declared in the original manifest payload.

        """
        return u.Infra.project_name_from_payload(
            project_dir / c.PYPROJECT_FILENAME, payload
        )

    @classmethod
    def _drift_issue(
        cls,
        pyproject: Path,
        expected: object,
        digest: str,
    ) -> m.Infra.Issue | None:
        """Build the blocking issue for one frozen-table drift.

        Returns:
            The operator-authorization diagnostic, or no issue only when the
            live digest matches the original catalog entry.

        """
        if expected is None:
            detail = "no catalog entry"
        elif expected != digest:
            detail = f"catalog={expected} live={digest}"
        else:
            return None
        return m.Infra.Issue(
            file=str(pyproject),
            line=1,
            column=1,
            code=f"{c.Infra.LINT_CONFIG_FREEZE}-drift",
            message=(
                "frozen lint-config table drifted from the operator catalog "
                f"({detail}); lint-rule changes require express operator "
                "authorization (AGENTS.md: Lint-Rule Change Freeze, 2026-10-28)"
            ),
            severity=c.Infra.GateSeverity.ERROR.value,
        )


__all__: list[str] = ["FlextInfraGatesLintConfigFreeze"]
