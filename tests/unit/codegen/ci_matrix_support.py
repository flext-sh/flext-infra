from __future__ import annotations

from pathlib import Path

import pytest

from flext_infra import infra, m
from flext_infra.codegen import (
    FlextInfraCodegenConformExecute,
    FlextInfraCodegenMakeBootstrap,
)
from tests import c, tm, u


class TestsFlextInfraCodegenCiMatrixSupport:
    """Render one fresh internal_flext project for CI matrix contract classes."""

    @staticmethod
    def render_project(root: Path) -> Path:
        """Render one fresh internal_flext project into root and return it.

        Returns:
            The resulting ``Path``.

        """
        root.mkdir(parents=True, exist_ok=True)
        repository = u.Tests.repository_ref(
            "flext-demo", role=c.Infra.MakeProfile.STANDALONE
        )
        if not (root / c.Infra.GIT_DIR).exists():
            integration = u.Tests.integration()
            u.Tests.initialize_unborn_git_repo(
                root,
                origin_url=repository.url,
                branch=integration.branch,
            )
            u.Tests.copy_tracked_mise_seeds(root)
            u.Tests.write_project_beads_config(root, repository.name)
            declaration = m.Infra.RepositoryDeltaSpec(
                project=u.Tests.project_spec(repository.name).model_copy(
                    update={"upstream": "flext_cli"}
                ),
                integration=integration,
                kind=repository.kind,
            )
            tm.ok(
                u.Cli.yaml_dump(
                    root / c.CONFIG_DIR_NAME / c.Infra.CODEGEN_CONFIG_FILENAME,
                    {
                        "Infra": {
                            "codegen": {
                                "repository": declaration.model_dump(
                                    mode="json", exclude_unset=True
                                ),
                            },
                        },
                    },
                )
            )
            service = FlextInfraCodegenMakeBootstrap(
                repository_root=root,
                kind=repository.kind,
                apply_changes=True,
            )
            tm.ok(service.execute(), eq=True)
        else:
            tm.ok(
                FlextInfraCodegenConformExecute.execute_request(
                    u.Tests.conform_request(
                        root,
                        what=c.Infra.CodegenConformSurface.ALL,
                        scope=c.Infra.CodegenConformScope.SELF,
                        mode=c.Infra.CodegenConformMode.APPLY,
                    ),
                    execution_context=infra,
                ),
            )
        return root

    @staticmethod
    @pytest.fixture(scope="class")
    def rendered_project(tmp_path_factory: pytest.TempPathFactory) -> Path:
        """Render one fresh internal_flext project for the class's read-only cases.

        Every read-only case asserts the identical generated bytes regardless
        of which fresh render it inspects, so the expensive scaffold is
        provisioned once per contract class instead of once per case. Cases
        that prove repeated-render behavior render their own roots.

        Returns:
            The resulting ``Path``.

        """
        return TestsFlextInfraCodegenCiMatrixSupport.render_project(
            tmp_path_factory.mktemp("ci-matrix-render"),
        )


__all__: list[str] = ["TestsFlextInfraCodegenCiMatrixSupport"]
